-- Chat'Perlipopette : disponibilité manuelle et réservations datées
create table if not exists public.catalogue_game_availability (
  game_code text primary key,
  blocked_manually boolean not null default false,
  block_reason text,
  updated_at timestamptz not null default now()
);

create table if not exists public.game_reservations (
  id bigint generated by default as identity primary key,
  game_code text not null,
  game_name text not null,
  date_debut date not null,
  date_retour date not null,
  status text not null default 'pending',
  customer_email text,
  created_at timestamptz not null default now(),
  constraint game_reservations_dates_valid check (date_retour >= date_debut),
  constraint game_reservations_status_valid check (status in ('pending','confirmed','cancelled','completed'))
);

create index if not exists game_reservations_game_dates_idx
  on public.game_reservations (game_code, date_debut, date_retour);

alter table public.catalogue_game_availability enable row level security;
alter table public.game_reservations enable row level security;
